// JSON is the editable source. Compile it into the eagerly imported module so
// selecting a mansion/expanding a reading never initiates a fetch.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
function build() {
  const data = JSON.parse(fs.readFileSync(path.join(root, 'data/nakshatra_interpretation.json'), 'utf8'));
  return '// Generated by node scripts/build-interpretation.cjs; edit the JSON, not this file.\n'
    + 'export const INTERPRETATIONS = ' + JSON.stringify(data, null, 2) + ';\n';
}
module.exports = { build };
if (require.main === module) fs.writeFileSync(path.join(root, 'interpretation-data.js'), build());
